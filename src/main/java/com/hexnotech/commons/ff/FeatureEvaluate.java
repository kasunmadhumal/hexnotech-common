package com.hexnotech.commons.ff;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

@Target({ElementType.METHOD, ElementType.TYPE})
@Retention(RetentionPolicy.RUNTIME)
public @interface FeatureEvaluate {
    
    boolean byPass() default false;
    String featureName();
    boolean ifMissing() default false;
    boolean considerCarrier() default false;
    String carrierExpression() default "";
    String disabledMessage() default "";

}
